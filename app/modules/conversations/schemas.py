from pydantic import BaseModel, ConfigDict, Field
from typing import Literal
from datetime import datetime


class ConversationCreate(BaseModel):
    scope: Literal["research", "workspace"]
    research_id: str | None = None
    title: str | None = Field(default=None, max_length=255)


class MessageCreate(BaseModel):
    content: str = Field(min_length=1)


class ConversationResponse(BaseModel):
    model_config = ConfigDict(from_attributes=True)

    id: str
    scope: str
    research_id: str | None
    title: str | None
    created_at: datetime
    updated_at: datetime


class MessageResponse(BaseModel):
    model_config = ConfigDict(from_attributes=True)

    id: str
    conversation_id: str
    role: str
    content: str
    citations: list[dict] | None
    message_metadata: dict | None
    created_at: datetime


class ConversationDetailResponse(ConversationResponse):
    messages: list[MessageResponse]


class ConversationListResponse(BaseModel):
    items: list[ConversationResponse]
    total: int
    page: int
    limit: int
    has_next: bool


class ChatCitation(BaseModel):
    number: int
    source_id: str
    research_id: str
    title: str | None = None
    url: str | None = None


class ChatAnswerResult(BaseModel):
    answer: str
    citations: list[ChatCitation] = Field(default_factory=list)
    model: str | None = None
    usage: dict | None = None
    cost: float | None = None
    cost_details: dict | None = None


from pydantic import BaseModel, ConfigDict, Field


class ChatAnswerOutput(BaseModel):
    """Structured response generated by the research chat model."""

    model_config = ConfigDict(extra="forbid")

    answer: str = Field(
        description=(
            "The complete user-facing answer in Markdown. "
            "Use inline numeric citations such as [1] where supported."
        )
    )

    citations: list[int] = Field(
        description=(
            "Unique, positive source numbers actually cited in the answer. "
            "Only use source numbers provided in the research context."
        )
    )

    suggested_questions: list[str] = Field(
        max_length=3,
        description=(
            "Up to 3 concise and relevant follow-up questions. "
            "Generate them based on the answer and current research context. "
            "Avoid repetition. Return an empty list if no useful "
            "follow-up question can be suggested."
        ),
    )


class MessageFeedbackCreate(BaseModel):
    rating: Literal["positive", "negative"]


class MessageFeedbackResponse(BaseModel):
    model_config = ConfigDict(from_attributes=True)

    message_id: str
    rating: Literal["positive", "negative"]
